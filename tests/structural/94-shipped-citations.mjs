// A shipped file may not point its reader at something the reader did not receive. Seven did: four
// cited structural test modules by number, two an installer script outside the delivery allowlist,
// one a document under this repo's own docs tree. Each is the same small harm — a citation that
// resolves for the author and 404s for the reader — and each was found by an audit somebody
// remembered to run. This is that scan as a check.
//
// WHAT IT DOES NOT FLAG, on purpose. `docs/pitch.md` in a skill's invocation example is the USER's
// pitch, not this repo's documentation, and a rule that keyed on "a path that resolves to a real
// file here" reddened exactly that: the translator's `--glossary docs/glossary.md` example collides
// by coincidence with a file this repo happens to have. So the rule keys on directories a consumer
// has no analogue for, and on this repo's own documentation structure (a `docs/` path with a
// subdirectory), never on a flat `docs/<file>` operand.
import { readFileSync, writeFileSync, mkdtempSync, rmSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, dirname } from "node:path";
import { execFileSync } from "node:child_process";

/** Directories that exist only in this repository — a consumer has nothing they could name. */
const REPO_ONLY = /(?:^|[\s(\[`'"])((?:tests|tools|evals|traces)\/[A-Za-z0-9_.\/-]+)/g;
/** This repo's own documentation structure: `docs/<dir>/<file>`. A flat `docs/<file>` is an operand. */
const DEEP_DOCS = /(?:^|[\s(\[`'"])(docs\/[A-Za-z0-9_.-]+\/[A-Za-z0-9_.\/-]+)/g;
const SCANNED = /\.(md|mjs|js|json)$/;

/**
 * Every citation of an unshipped artifact in one file's text.
 * @param {string} text - The file's contents.
 * @returns {string[]} The cited paths, in order.
 */
export function unshippedCitations(text) {
  const out = [];
  for (const re of [REPO_ONLY, DEEP_DOCS]) {
    re.lastIndex = 0;
    let m;
    while ((m = re.exec(text))) out.push(m[1].replace(/[.,)\]]+$/, ""));
  }
  return out;
}

export async function run(ctx) {
  const { ROOT, ok, fail, section } = ctx;
  section("146. No shipped file cites an artifact the reader did not receive");

  // The delivery allowlist is the authority on what ships — derived, never listed here.
  const allowlist = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")).files;
  if (!Array.isArray(allowlist) || !allowlist.length) { fail("package.json declares no `files` allowlist — the shipped set cannot be derived"); return; }
  const shipped = execFileSync("git", ["ls-files", ...allowlist], { cwd: ROOT, encoding: "utf8" })
    .trim().split("\n").filter((f) => f && SCANNED.test(f));
  if (shipped.length < 20) { fail(`the shipped set derived to only ${shipped.length} scannable files — the derivation is wrong, not the tree`); return; }

  const offenders = [];
  for (const f of shipped) {
    for (const cited of unshippedCitations(readFileSync(join(ROOT, f), "utf8"))) offenders.push(`${f} → ${cited}`);
  }
  if (!offenders.length) {
    ok(`none of the ${shipped.length} shipped text files cites tests/, tools/, evals/, traces/ or this repo's own docs tree`);
  } else {
    fail(`a shipped file points its reader at something the reader does not have:\n  ${offenders.slice(0, 12).join("\n  ")}`
      + (offenders.length > 12 ? `\n  …and ${offenders.length - 12} more` : "")
      + "\n  Keep the operative rationale, drop the evidence: say WHY the code is shaped that way without naming an artifact the reader cannot open.");
  }

  // A check that cannot go red reads as coverage it does not provide. Seed each class and watch.
  const seeded = [
    ["a structural test module by number", "See tests/structural/80-citation-rehash.mjs for the fixture."],
    ["a repo-only tool", "Regenerated by tools/demo/record-demo.mjs."],
    ["this repo's own design document", "The tiers are in docs/design/03-system-design.md."],
  ];
  const missed = seeded.filter(([, text]) => unshippedCitations(text).length === 0);
  if (!missed.length) ok("the scan catches all three classes the audit found — a test module, a repo-only tool, a document in this repo's docs tree");
  else fail(`the scan is blind to: ${missed.map(([label]) => label).join(", ")}`);

  const allowed = [
    ["a user's pitch as an invocation operand", "/ba-pitch-analyzer docs/pitch.md"],
    ["a user's glossary as a flag value", "/translator --glossary docs/glossary.md docs/pitch.md"],
    ["a consumer's own intake directory", "/translator docs/intake/"],
  ];
  const wrongly = allowed.filter(([, text]) => unshippedCitations(text).length > 0);
  if (!wrongly.length) ok("a flat docs/<file> operand is not flagged — that is the user's document, not this repo's");
  else fail(`the scan reds a legitimate consumer path: ${wrongly.map(([label]) => label).join(", ")}`);

  // And it reads the allowlist rather than a hard-coded set: a file moved out of the shipped set
  // stops being scanned, and one moved in starts.
  const ws = mkdtempSync(join(tmpdir(), "shipped-cites-"));
  try {
    execFileSync("git", ["init", "-q", "-b", "main"], { cwd: ws });
    writeFileSync(join(ws, "package.json"), JSON.stringify({ name: "x", version: "0.0.0", files: ["skills/"] }));
    mkdirSync(dirname(join(ws, "skills/demo/SKILL.md")), { recursive: true });
    writeFileSync(join(ws, "skills/demo/SKILL.md"), "Read tools/demo/record-demo.mjs first.\n");
    mkdirSync(dirname(join(ws, "docs/design/note.md")), { recursive: true });
    writeFileSync(join(ws, "docs/design/note.md"), "Read tools/demo/record-demo.mjs first.\n");
    execFileSync("git", ["add", "-A"], { cwd: ws });
    const shippedThere = execFileSync("git", ["ls-files", "skills/"], { cwd: ws, encoding: "utf8" }).trim().split("\n");
    const hits = shippedThere.flatMap((f) => unshippedCitations(readFileSync(join(ws, f), "utf8")));
    if (hits.length === 1 && !shippedThere.includes("docs/design/note.md")) {
      ok("the scan follows the allowlist: the same sentence is a finding inside the shipped set and none outside it");
    } else fail(`the allowlist is not what bounds the scan: shipped=${JSON.stringify(shippedThere)} hits=${JSON.stringify(hits)}`);
  } finally {
    rmSync(ws, { recursive: true, force: true });
  }
}
