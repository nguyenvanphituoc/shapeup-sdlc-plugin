function run(label, content, env = {}, raw = false) {
  const d = join(root, 'c' + n++); mkdirSync(d);
  const f = join(d, 'content.json');
  if (content !== null) writeFileSync(f, raw ? content : JSON.stringify(content));
  const out = join(d, 'out');
  const r = spawnSync('node', [B], { env: { ...process.env, CONTENT_FILE: f, OUT_DIR: out, ...env }, encoding: 'utf8' });
  const html = existsSync(join(out, 'index.html')) ? readFileSync(join(out, 'index.html'), 'utf8') : null;
  console.log('=== ' + label + ' exit=' + r.status + ' stderr=' + JSON.stringify(r.stderr.slice(0, 200)) + ' html=' + (html ? html.length : 'none'));
  return html;
}
